                              # 2 Print Squares of Numbers from 1 to 5
# Question: Write a program to print the squares of numbers
# from 1 to 5.
# Expected Output: 1 4 9 16 25
# Hint: Use number ** 2 to get the square of each number in
# # the loop.

# answer

a =[1,2,3,4,5]
for n in a:
    print((n),"-",n**2," ",end=" ")