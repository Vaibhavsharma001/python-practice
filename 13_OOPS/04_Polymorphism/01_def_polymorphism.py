#------------------------------------------------------------------------|   
                   # What is Polymorphism? (English)
#------------------------------------------------------------------------|

# Definition:

# Polymorphism means "Many Forms."
# In Python, one method, function, or operator can perform different tasks depending on the object or data type.

# SIMPLE DEFINATION

# One interface, many implementations.
# It means the same method name can behave differently for different objects.

# Polymorphism क्या है? (Hindi)

# परिभाषा:

# Polymorphism का मतलब होता है "एक चीज़ के कई रूप"।

# Python में एक ही function, method या operator अलग-अलग objects के साथ अलग-अलग तरीके से काम करता है।

# आसान भाषा में

# एक नाम, कई काम।

# यानी एक ही Method अलग-अलग object के लिए अलग-अलग Result देता है।


