                              #IF ELIF ELSE STATEMENTS

# elif statement is used to check multiple conditions in a program. It executes a block of code when its condition evaluates to True after previous conditions evaluate to False.


num1 = eval(input("enter your number :-"))
if num1>=90:
    print("you are above 90")

elif num1>80:
     print("you are above 80")

elif num1>70:
     print("you are above 70")     

elif num1>60:
     print("you are above 60")

elif num1>50:
     print("you are above 50")

else:
     print("you are under 49")
