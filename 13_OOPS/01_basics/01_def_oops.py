#-------------------------------------------------------------------------------------------------------------------------|
                                                              # What is OOP? (English)
#-------------------------------------------------------------------------------------------------------------------------|

# Object-Oriented Programming (OOP) is a programming paradigm (style of programming) that organizes software around objects rather than functions or
# procedures.

# An object is a real-world entity that contains:

# Data (Attributes/Properties)|
# Behavior (Methods/Functions)

# OOP helps programmers write code that is:

# Reusable
# Modular

# Secure
# Easy to Maintain
# Easy to Scale

# Instead of writing everything in one file or one function, OOP divides a program into multiple objects that work together.

