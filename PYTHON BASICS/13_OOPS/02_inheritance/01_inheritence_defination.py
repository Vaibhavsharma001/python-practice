# 1. What is Inheritance? (English)

# Inheritance is one of the four fundamental principles (pillars) of Object-Oriented Programming (OOP).

# Inheritance allows a new class (Child Class) to acquire the properties (attributes) and behaviors (methods)I of an existing class (Parent Class).

# It helps in:

# Code Reusability
# Reducing Code Duplication
# Easy Maintenance
# Extending Existing Functionality
# Building Hierarchical Relationships
# Definition

# Inheritance is the process by which one class acquires the properties and methods of another class.

